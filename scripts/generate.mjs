#!/usr/bin/env node
// Writes the files that are generated from other files in the repo. `npm run check` fails when one of them
// is out of date, so run this after changing their source.
//
//   npm run generate            write them
//   npm run generate -- --check only report which are stale (exit 1 if any)
//
//   schemas/asset.schema.json   ← scripts/lib/manifest/spec.mjs
//   .github/CODEOWNERS          ← .github/owners.json + each figure's "maintainers"
import fs from 'node:fs';
import path from 'node:path';
import { ASSETS_DIR, ID_RE, ROOT } from './lib/paths.mjs';
import { MANIFEST_SCHEMA } from './lib/manifest/index.mjs';

const OWNERS_FILE = path.join(ROOT, '.github', 'owners.json');

/** CODEOWNERS: the platform owners own everything shared; each figure is also owned by its maintainers. */
export function codeowners() {
  const owners = fs.existsSync(OWNERS_FILE) ? JSON.parse(fs.readFileSync(OWNERS_FILE, 'utf8')).owners || [] : [];
  const at = (names) => names.map((n) => `@${n.replace(/^@/, '')}`).join(' ');
  const lines = ['# Generated by `npm run generate` from .github/owners.json and each figure\'s "maintainers". Do not edit by hand.', ''];
  if (!owners.length) lines.push('# No platform owners yet: add GitHub usernames to .github/owners.json, then run npm run generate.', '');
  if (owners.length) lines.push(`* ${at(owners)}`, '');
  const ids = fs.existsSync(ASSETS_DIR)
    ? fs
        .readdirSync(ASSETS_DIR)
        .filter((id) => ID_RE.test(id) && fs.existsSync(path.join(ASSETS_DIR, id, 'asset.json')))
        .sort()
    : [];
  for (const id of ids) {
    const m = JSON.parse(fs.readFileSync(path.join(ASSETS_DIR, id, 'asset.json'), 'utf8'));
    const who = [...new Set([...(m.maintainers || []), ...owners])];
    if (who.length) lines.push(`/assets/${id}/ ${at(who)}`);
  }
  if (owners.length) {
    lines.push('', '# Only the platform owners (and the studio) change these.');
    for (const p of [
      '/assets/*/status.json',
      '/shared/',
      '/scripts/',
      '/templates/',
      '/books/',
      '/schemas/',
      '/dashboard/',
      '/.github/',
      '/package.json',
      '/package-lock.json',
    ]) {
      lines.push(`${p} ${at(owners)}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

export function generatedFiles() {
  return [
    {
      file: path.join(ROOT, 'schemas', 'asset.schema.json'),
      source: 'scripts/lib/manifest/spec.mjs',
      content: `${JSON.stringify(MANIFEST_SCHEMA, null, 2)}\n`,
    },
    { file: path.join(ROOT, '.github', 'CODEOWNERS'), source: '.github/owners.json and asset.json maintainers', content: codeowners() },
  ];
}

/** The generated files whose content on disk differs from what they should be. */
export function staleFiles() {
  return generatedFiles().filter((g) => !fs.existsSync(g.file) || fs.readFileSync(g.file, 'utf8') !== g.content);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const checkOnly = process.argv.includes('--check');
  const stale = staleFiles();
  for (const g of stale) {
    const rel = path.relative(ROOT, g.file);
    if (checkOnly) console.log(`✗ ${rel} is out of date (from ${g.source}): run npm run generate`);
    else {
      fs.mkdirSync(path.dirname(g.file), { recursive: true });
      fs.writeFileSync(g.file, g.content);
      console.log(`✓ wrote ${rel}`);
    }
  }
  if (!stale.length) console.log('Generated files are up to date.');
  if (checkOnly && stale.length) process.exitCode = 1;
}
